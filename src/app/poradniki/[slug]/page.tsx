import Link from "next/link";
import Image from "next/image";
import {guideScreenshots} from "@/content/guideScreenshots";
import { Fragment } from "react";
import { notFound } from "next/navigation";
import { allGuides, getGuide, guideCategory, getCategory, getRelatedGuides, getGuideCounts } from "@/lib/guide-directory";
import { serviceMetadata } from "@/lib/seo";
import { getEnglishGuide } from "@/lib/guide-i18n";

type Props = { params: Promise<{ slug: string }> };
export const dynamicParams = true;
export const revalidate = 86400;
export function generateStaticParams() { return allGuides.slice(0, 100).map(({slug}) => ({slug})); }
export async function generateMetadata({params}: Props) {
  const {slug} = await params;
  const guide = getGuide(slug);
  if (!guide) notFound();
  const metadata = serviceMetadata(guide.title, guide.description, `poradniki/${slug}`);
  const englishEdition = getEnglishGuide(slug);
  const polishUrl = `https://bernecki.dev/poradniki/${slug}`;
  return {
    ...metadata,
    alternates: {
      canonical: polishUrl,
      ...(englishEdition ? { languages: { "pl-PL":polishUrl, en:`https://bernecki.dev/en/guides/${slug}` } } : {})
    }
  };
}
export default async function GuidePage({params}: Props) {
  const {slug} = await params;
  const guide = getGuide(slug);
  if (!guide) notFound();
  const isAuto = "autoGenerated" in guide && guide.autoGenerated === true;
  const screenshots = guideScreenshots[slug] ?? [];
  const currentCategory = guideCategory(guide);
  const nearbyCategories = getGuideCounts().filter(item => item.slug !== currentCategory && item.count > 0).sort((a,b)=>b.count-a.count).slice(0,5);
  const relatedGuides = getRelatedGuides(slug, 10);
  const url = `https://bernecki.dev/poradniki/${slug}`;
  const data = {"@context":"https://schema.org", "@graph":[
    {"@type":"Article", "@id":`${url}#article`, headline:guide.title, description:guide.description, articleSection:("category" in guide ? guide.category : getCategory(guideCategory(guide))?.label), mainEntityOfPage:url, inLanguage:"pl-PL", isAccessibleForFree:true, author:isAuto ? {"@type":"Organization",name:"bernecki.dev",url:"https://bernecki.dev/"} : {"@type":"Person", "@id":"https://bernecki.dev/#person", name:"Kacper Bernecki", url:"https://bernecki.dev/"}, image: screenshots.length ? `https://bernecki.dev${screenshots[0].src}` : "https://bernecki.dev/opengraph-image"},
    {"@type":"BreadcrumbList",itemListElement:[{"@type":"ListItem",position:1,name:"Kacper Bernecki",item:"https://bernecki.dev/"},{"@type":"ListItem",position:2,name:"Poradniki",item:"https://bernecki.dev/poradniki"},{"@type":"ListItem",position:3,name:guide.title,item:url}]}
  ]};
  return <main className="site-page editorial-page mx-auto max-w-4xl px-5 pb-24 pt-36 md:px-8">
    <script type="application/ld+json" dangerouslySetInnerHTML={{__html:JSON.stringify(data).replace(/</g,"\\u003c")}} />
    <nav aria-label="Ścieżka strony" className="page-breadcrumb flex flex-wrap gap-2 text-sm"><Link href="/">Kacper Bernecki</Link><span>/</span><Link href="/poradniki">Poradniki</Link><span>/</span><Link href={`/poradniki/tematy/${currentCategory}`}>{getCategory(currentCategory)?.label}</Link></nav>
    <p className="mt-5 text-sm text-white/65">Kategoria: <Link className="underline underline-offset-4" href={`/poradniki/tematy/${guideCategory(guide)}`}>{getCategory(guideCategory(guide))?.label}</Link></p>
    <article>
      <h1 className="mt-8 text-4xl leading-tight md:text-5xl">{guide.title.split(/([_/])/).map((part,i)=><Fragment key={i}>{part}{part==="_"||part==="/"?<wbr/>:null}</Fragment>)}</h1>
      <p className="mt-5 text-sm text-white/70">{currentCategory === "biznes-podatki" ? "Poradnik dla przedsiębiorców" : "Poradnik techniczny"} · <Link href="/#about" className="underline underline-offset-4">Kacper Bernecki</Link></p>
      <p className="surface-card mt-8 rounded-2xl border border-white/25 bg-[var(--brand-black)] p-6 text-lg leading-8 text-white">{guide.intro}</p>
      {screenshots.length > 0 && <section className="mt-10" aria-labelledby="real-screenshots-heading">
        <h2 id="real-screenshots-heading" className="text-2xl text-white">Przykład komunikatu błędu</h2>
        <p className="mt-3 leading-7 text-white/70">Tak może wyglądać problem w panelu. Dokładną przyczynę ustalisz, wykonując poniższe kroki diagnostyczne.</p>
        <div className="mt-5 flex flex-wrap gap-5">{screenshots.map((shot) => <figure key={shot.src} className="surface-card w-full max-w-xl overflow-hidden rounded-2xl border border-white/15 bg-[var(--brand-black)]">
          <a href={shot.src} target="_blank" rel="noopener noreferrer" aria-label="Powiększ przykład komunikatu błędu">
            <Image src={shot.src} alt={shot.alt} width={shot.width} height={shot.height} sizes="(max-width: 640px) 100vw, 540px" className="h-auto w-full object-contain" />
          </a>
          <figcaption className="px-5 py-4 text-sm leading-6 text-white/70">{shot.caption}</figcaption>
        </figure>)}</div>
      </section>}
      <nav aria-label="Spis treści" className="surface-card my-10 rounded-xl border border-white/10 p-6"><p className="mb-4 text-white">W tym poradniku</p><ol className="list-inside list-decimal space-y-3 text-white">{guide.sections.map((s,i)=><li key={s.title}><a href={`#sekcja-${i+1}`} className="underline underline-offset-4">{s.title.replace(/^\d+\.\s*/, "")}</a></li>)}</ol></nav>
      {guide.sections.map((s,i)=><section key={s.title} id={`sekcja-${i+1}`} className="mt-12 scroll-mt-28"><h2 className="text-2xl text-white md:text-3xl">{s.title}</h2>{s.paragraphs.map(p=><p key={String(p)} className="mt-5 leading-8 text-white">{String(p)}</p>)}</section>)}
      {"sources" in guide && guide.sources && <aside className="surface-card mt-12 rounded-xl border border-white/15 p-5"><h2 className="text-lg">Dokumentacja i źródła</h2><ul className="mt-3 space-y-2">{guide.sources.map((source)=><li key={source.url}><a className="text-sm text-[var(--brand-accent)] underline underline-offset-4" href={source.url} target="_blank" rel="noopener noreferrer">{source.label}</a></li>)}</ul></aside>}
    </article>
    <aside className="surface-card mt-14 rounded-2xl border border-white/30 bg-[var(--brand-black)] p-7"><h2 className="text-2xl">Przełóżmy to na Twoją firmę.</h2><p className="mt-4 leading-7 text-white/70">Opisz swój cel, obecne rozwiązanie i termin. Ustalimy, czego potrzebujesz na start.</p><div className="mt-6 flex flex-wrap gap-5"><a href={`mailto:kacper@bernecki.dev?subject=${encodeURIComponent(guide.title)}`} className="rounded-lg brand-action px-5 py-3 text-black">Napisz o projekcie</a><Link href={guide.service} className="py-3 text-white">{guide.serviceLabel} →</Link></div></aside>
    <nav aria-label="Powiązane poradniki" className="mt-14">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <h2 className="text-2xl">Powiązane rozwiązania</h2>
        <Link href={`/poradniki/tematy/${currentCategory}`} className="text-sm text-white underline underline-offset-4">Więcej w kategorii: {getCategory(currentCategory)?.label}</Link>
      </div>
      <div className="mt-6 grid gap-3 md:grid-cols-2">
        {relatedGuides.map(item => <Link key={item.slug} href={`/poradniki/${item.slug}`} className="surface-card block rounded-xl border border-white/15 p-4 transition-colors hover:border-white/50">
          <span className="text-xs text-white/60">{getCategory(guideCategory(item))?.label}</span>
          <p className="mt-2 font-medium leading-snug text-white">{item.title}</p>
          <p className="mt-2 text-sm leading-6 text-white/65">{item.description}</p>
        </Link>)}
      </div>
    </nav>
    <nav aria-label="Pozostałe kategorie poradników" className="mt-10 border-t border-white/20 pt-8">
      <h2 className="text-xl">Inne obszary, które mogą pomóc</h2>
      <div className="mt-4 flex flex-wrap gap-x-6 gap-y-3 text-sm">
        {nearbyCategories.map(item => <Link key={item.slug} href={`/poradniki/tematy/${item.slug}`} className="text-white underline underline-offset-4">{item.label} ({item.count})</Link>)}
        <Link href="/poradniki" className="text-white underline underline-offset-4">Pełna baza poradników</Link>
      </div>
    </nav>
  </main>;
}
