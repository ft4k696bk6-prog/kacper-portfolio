import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(import.meta.dirname,"..");
const read=(p)=>JSON.parse(readFileSync(resolve(root,p),"utf8"));
const entries=read("src/content/pseo/autopilot-published.json");
const state=read("docs/pseo-autopilot-state.json");
const norm=(s)=>String(s).toLowerCase().replace(/ł/g,"l").normalize("NFKD").replace(/[\u0300-\u036f]/g,"").replace(/[^a-z0-9]+/g," ").trim();
const allowed=["nextjs.org","react.dev","supabase.com","vercel.com","github.com","docs.github.com","developers.google.com","support.google.com","developer.wordpress.org","wordpress.org","docs.npmjs.com","support.apple.com","developer.apple.com","developers.facebook.com","web.dev","developer.mozilla.org","www.postgresql.org","www.typescriptlang.org","nodejs.org","openrouter.ai","developers.cloudflare.com"];
const seenSlugs=new Set(),seenTitles=new Set();
let errors=0;
function fail(slug,reason){console.error("pSEO QA: "+slug+": "+reason);errors++;}
for(const e of entries){
 if(!e||typeof e!=="object"){fail("unknown","invalid record");continue;}
 if(e.status!=="published"||e.autoGenerated!==true)fail(e.slug,"invalid publication status");
 if(typeof e.slug!=="string"||!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(e.slug))fail(e.slug,"invalid slug");
 if(seenSlugs.has(e.slug))fail(e.slug,"duplicate slug");
 seenSlugs.add(e.slug);
 const n=norm(e.title);
 if(seenTitles.has(n))fail(e.slug,"duplicate title");
 seenTitles.add(n);
 if(typeof e.title!=="string"||e.title.length<32||e.title.length>125||typeof e.intro!=="string"||e.intro.length<220)fail(e.slug,"title/intro incomplete");
 if(typeof e.description!=="string"||e.description.length<90)fail(e.slug,"description incomplete");
 const fields={diagnostics:2,steps:5,verification:2,mistakes:1};
 for(const [k,min] of Object.entries(fields))if(!Array.isArray(e[k])||e[k].length<min||e[k].some(p=>typeof p!=="string"||p.length<65))fail(e.slug,k+" incomplete");
 if(!Array.isArray(e.sources)||!e.sources.length||e.sources.some(s=>{
  try{const u=new URL(s.url);return u.protocol!=="https:"||!allowed.some(h=>u.hostname===h||u.hostname.endsWith("."+h));}catch{return true;}
 }))fail(e.slug,"source not in official allowlist");
 const text=JSON.stringify(e);
 if(/\b(sk-[a-z0-9]{15,}|gh[pousr]_[a-z0-9]{20,}|eyJ[A-Za-z0-9_-]{30,}\.)/i.test(text))fail(e.slug,"potential secret");
}
if(!Array.isArray(state.usedTopics)||!Array.isArray(state.rejectedTopics)||!Array.isArray(state.seenIssueUrls))fail("state","broken state file");
console.log("pSEO validated auto-published articles: "+entries.length+", errors: "+errors);
if(errors)process.exitCode=1;
